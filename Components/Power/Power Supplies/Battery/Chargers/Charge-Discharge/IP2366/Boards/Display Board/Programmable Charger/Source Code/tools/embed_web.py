"""Deterministic, dependency-free embedding of the self-contained web UI."""
from pathlib import Path
import gzip

if '__file__' in globals():
    project = Path(__file__).resolve().parents[1]
else:
    # PlatformIO executes extra scripts via SCons, without __file__.
    Import('env')
    project = Path(env.subst('$PROJECT_DIR'))
page = (project / 'web/index.html').read_bytes()
font = (project / 'web/assets/montserrat-latin.woff2').read_bytes()
assert font[:4] == b'wOF2'

def array(name, data):
    rows = [','.join(f'0x{b:02x}' for b in data[i:i+24]) for i in range(0, len(data), 24)]
    return f'static const uint8_t {name}[] PROGMEM={{\n' + ',\n'.join(rows) + '\n};\n'

compressed = gzip.compress(page, compresslevel=9, mtime=0)
content = '// Generated by tools/embed_web.py; edit web/index.html instead.\n#pragma once\n#include <stdint.h>\nnamespace batcharger {\n'
content += array('WebPageGzip', compressed) + array('WebFont', font) + '} // namespace batcharger\n'
target = project / 'include/web_page.h'
if not target.exists() or target.read_text() != content:
    target.write_text(content)
print(f'Web UI: {len(page)} bytes source, {len(compressed)} bytes gzip; font: {len(font)} bytes WOFF2')
